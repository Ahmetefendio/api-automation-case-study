package com.nesine.api.model;

public class Outcome {

    private String id;
    private String name;
    private String mbs;
    private String odd;
    private String status;

    public String getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getMbs() {
        return mbs;
    }

    public String getOdd() {
        return odd;
    }

    public String getStatus() {
        return status;
    }
}
